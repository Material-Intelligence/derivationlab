export const messageCatalog: Record<UiLocale, Catalog> = { en, "zh-CN": zhCN };

function isUiLocale(value: unknown): value is UiLocale {
  return value === "en" || value === "zh-CN";
}

export function readStoredLocale(storage: Pick<Storage, "getItem"> | null | undefined = globalThis.localStorage): UiLocale {
  try {
    const value = storage?.getItem(UI_LOCALE_STORAGE_KEY);
    return isUiLocale(value) ? value : "en";
  } catch {
    return "en";
  }
}

interface LocaleContextValue {
  locale: UiLocale;
  messages: Catalog;
  setLocale: (locale: UiLocale) => void;
  formatDateTime: (value: string | Date) => string;
}

const defaultLocaleValue: LocaleContextValue = {
  locale: "en",
  messages: en,
  setLocale: () => undefined,
  formatDateTime: (value) => new Intl.DateTimeFormat("en", { dateStyle: "medium", timeStyle: "short" }).format(new Date(value)),
};

const LocaleContext = createContext<LocaleContextValue>(defaultLocaleValue);

export function LocaleProvider({ host, children }: { host: ProductHost; children: ReactNode }) {
  const [locale, setLocaleState] = useState<UiLocale>(() => readStoredLocale());
  const setLocale = useCallback((nextLocale: UiLocale) => {
    setLocaleState(nextLocale);
    try {
      window.localStorage.setItem(UI_LOCALE_STORAGE_KEY, nextLocale);
    } catch {
      // A blocked storage surface must not prevent an in-session language change.
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale;
    void host.setUiLocale?.(locale);
  }, [host, locale]);

  const value = useMemo<LocaleContextValue>(() => ({
    locale,
    messages: messageCatalog[locale],
    setLocale,
    formatDateTime: (input) => new Intl.DateTimeFormat(locale, { dateStyle: "medium", timeStyle: "short" }).format(new Date(input)),
  }), [locale, setLocale]);

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLocale() {
  return useContext(LocaleContext);
}
